function sourceOverrides(language: NonEnglishSourceLanguage): SourceNamespaceTranslations {
  const copy = accuracySourceCopy[language]
  const discovery = discoverySourceOverrides[language]

  return {
    auth: {
      [recoveryPhraseKey]: copy.recoveryPhrase,
    },
    common: {
      ...commonSourceOverrides(language),
      [torCallUnavailableKey]: copy.torCallUnavailable,
    },
    contacts: discovery.contacts,
    profile: discovery.profile,
    settings: {
      [torConfirmationKey]: copy.torConfirmation,
      [torActiveKey]: copy.torActive,
      [spectreSetupKey]: copy.spectreSetup,
      [torScopeKey]: copy.torScope,
      [secureStorageKey]: copy.secureStorage,
    },
    tor: {
      [torPresenceKey]: copy.torPresence,
    },
  }
}

function commonSourceOverrides(language: NonEnglishSourceLanguage) {
  return {
    ...cryptoHomeCommonOverrides[language],
    ...fiatCurrencyCommonOverrides[language],
    ...transactionOutcomeCommonOverrides[language],
  }
}

function completeSourceTranslations(translations: SourceNamespaceTranslations): LanguageTranslations {
  const completed = createEmptyNamespaces()

  for (const namespace of APP_NAMESPACES) {
    Object.assign(completed[namespace], en[namespace], translations[namespace] ?? {})
  }

  return completed
}

